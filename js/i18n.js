export const LANGS = [['fr', 'Français'], ['en', 'English'], ['es', 'Español (Latinoamérica)']];
const LOCALES = { fr: 'fr-FR', en: 'en-US', es: 'es-419' };
const KEY = 'pastel.lang';

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (DICT[saved]) return saved;
  } catch { /* navigation privée */ }
  for (const l of navigator.languages || [navigator.language || 'fr']) {
    const base = String(l).toLowerCase().slice(0, 2);
    if (DICT[base]) return base;
  }
  return 'en';
}

export let lang = detect();
export const locale = () => LOCALES[lang];

export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.fr[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}

// Textes fixes du HTML : data-i18n (contenu) et data-i18n-aria (aria-label).
export function applyStatic(root = document) {
  document.documentElement.lang = locale();
  for (const n of root.querySelectorAll('[data-i18n]')) n.textContent = t(n.dataset.i18n);
  for (const n of root.querySelectorAll('[data-i18n-aria]')) n.setAttribute('aria-label', t(n.dataset.i18nAria));
}

export function setLang(l) {
  if (!DICT[l] || l === lang) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* navigation privée */ }
  applyStatic();
  dispatchEvent(new Event('langchange'));
}
